#!/usr/bin/env node
/**
 * Build-time sitemap generator cho course detail URLs.
 *
 * Hits live API ở https://holilihu.online/api/v3/courses (paginated) → fetch
 * tất cả published courses → write fe/public/sitemap-courses.xml.
 *
 * Run:
 *   node scripts/generate-sitemap-courses.mjs
 *
 * Auto-skip nếu API unreachable (dev local) — không block build. Production
 * deploy script (deploy.sh) có thể trigger này hoặc CI runs trước build.
 *
 * Tương lai: switch sang `BASE_URL` env var để dev/staging point khác nhau.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUTPUT_FILE = resolve(__dirname, '..', 'public', 'sitemap-courses.xml');
const BASE_URL = process.env.SITEMAP_BASE_URL || 'https://holilihu.online';
const API_URL = `${BASE_URL}/api/v3/courses`;
const PAGE_SIZE = 100; // Max courses per page

function escapeXml(s) {
  return s.replace(/[<>&'"]/g, (c) => ({
    '<': '&lt;', '>': '&gt;', '&': '&amp;', "'": '&apos;', '"': '&quot;'
  }[c]));
}

async function fetchAllCourses() {
  const courses = [];
  let page = 0;
  let totalPages = 1;
  while (page < totalPages) {
    const url = `${API_URL}?page=${page}&size=${PAGE_SIZE}`;
    const res = await fetch(url, { headers: { 'Accept': 'application/json' } });
    if (!res.ok) {
      throw new Error(`API ${url} returned ${res.status}`);
    }
    const json = await res.json();
    // ApiResponse wrapper { success, data: { content, totalPages, ... } }
    const data = json.data || json;
    const content = data.content || [];
    courses.push(...content);
    totalPages = data.totalPages || 1;
    page++;
    if (content.length === 0) break;
  }
  return courses;
}

function generateSitemap(courses) {
  const today = new Date().toISOString().slice(0, 10);
  const urls = courses
    .filter(c => c.id && c.status !== 'DRAFT' && c.status !== 'ARCHIVED')
    .map(c => {
      const lastmod = c.updatedAt ? c.updatedAt.slice(0, 10) : today;
      return `  <url>
    <loc>${BASE_URL}/courses/${escapeXml(c.id)}</loc>
    <lastmod>${lastmod}</lastmod>
    <changefreq>weekly</changefreq>
    <priority>0.8</priority>
  </url>`;
    })
    .join('\n');

  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Auto-generated by scripts/generate-sitemap-courses.mjs at ${new Date().toISOString()} -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls}
</urlset>
`;
}

async function main() {
  try {
    console.log(`[sitemap-courses] Fetching ${API_URL}...`);
    const courses = await fetchAllCourses();
    console.log(`[sitemap-courses] Got ${courses.length} courses`);
    const xml = generateSitemap(courses);
    writeFileSync(OUTPUT_FILE, xml, 'utf-8');
    console.log(`[sitemap-courses] Wrote ${OUTPUT_FILE} (${xml.length} bytes)`);
  } catch (err) {
    console.warn(`[sitemap-courses] WARN: ${err.message}`);
    console.warn('[sitemap-courses] Skipping — production sitemap-courses.xml may be stale.');
    // Don't fail build — write empty stub if file missing
    try {
      writeFileSync(OUTPUT_FILE, `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"></urlset>
`, { flag: 'wx' });
      console.log(`[sitemap-courses] Wrote empty stub.`);
    } catch (writeErr) {
      // File exists, leave it
    }
  }
}

main();
